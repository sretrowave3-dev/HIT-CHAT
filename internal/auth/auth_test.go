func TestDeviceAuthorizationFlow(t *testing.T) {
	tokenMgr := NewTokenManager("test-secret-key-32-chars-campus!")
	dfm := NewDeviceFlowManager(tokenMgr, "http://localhost:8080/pair")

	req := &protocol.DeviceCodeRequest{
		ClientID:          "cli-device-101",
		Platform:          "cli",
		PublicIdentityKey: "base64pubkey==",
	}

	// 1. Request code
	resp, err := dfm.RequestCode(req)
	if err != nil {
		t.Fatalf("RequestCode failed: %v", err)
	}

	if !strings.HasPrefix(resp.UserCode, "CNET-") {
		t.Fatalf("expected user code format CNET-XXXX-XXXX, got %s", resp.UserCode)
	}

	// 2. Poll token before approval -> should return ErrDevicePending
	_, err = dfm.PollToken(resp.DeviceCode, req.ClientID)
	if err != protocol.ErrDevicePending {
		t.Fatalf("expected ErrDevicePending, got: %v", err)
	}

	// 3. User verifies user code on web portal
	err = dfm.VerifyUserCode(resp.UserCode, "student_alice")
	if err != nil {
		t.Fatalf("VerifyUserCode failed: %v", err)
	}

	// 4. Poll token after approval -> should succeed with valid JWT
	tokenResp, err := dfm.PollToken(resp.DeviceCode, req.ClientID)
	if err != nil {
		t.Fatalf("PollToken after authorization failed: %v", err)
	}

	if tokenResp.AccessToken == "" {
		t.Fatal("empty access token returned")
	}

	// 5. Validate token claims
	claims, err := tokenMgr.ValidateToken(tokenResp.AccessToken)
	if err != nil {
		t.Fatalf("token validation failed: %v", err)
	}

	if claims.UserHandle != "student_alice" {
		t.Fatalf("claims userHandle mismatch: got %s, want student_alice", claims.UserHandle)
	}
}

func TestPreKeyBundleRegistry(t *testing.T) {
	reg := NewBundleRegistry()

	bundle := &protocol.PreKeyBundle{
		DeviceID:        "dev-123",
		UserHandle:      "student_bob",
		IdentityKey:     "ik_pub_key",
		SignedPreKey:    "spk_pub_key",
		SignedPreKeySig: "spk_signature",
		OneTimePreKeys:  []string{"otk_1", "otk_2"},
	}

	if err := reg.RegisterBundle(bundle); err != nil {
		t.Fatalf("failed to register bundle: %v", err)
	}

	// Fetch 1: should return otk_1
	f1, err := reg.FetchBundle("student_bob")
	if err != nil {
		t.Fatalf("fetch 1 failed: %v", err)
	}
	if f1.SelectedOneTimePreKey != "otk_1" {
		t.Fatalf("expected otk_1, got %s", f1.SelectedOneTimePreKey)
	}

	// Fetch 2: should return otk_2
	f2, err := reg.FetchBundle("student_bob")
	if err != nil {
		t.Fatalf("fetch 2 failed: %v", err)
	}
	if f2.SelectedOneTimePreKey != "otk_2" {
		t.Fatalf("expected otk_2, got %s", f2.SelectedOneTimePreKey)
	}

	// Fetch 3: OTKs exhausted, returns empty selected OTK
	f3, err := reg.FetchBundle("student_bob")
	if err != nil {
		t.Fatalf("fetch 3 failed: %v", err)
	}
	if f3.SelectedOneTimePreKey != "" {
		t.Fatalf("expected empty OTK, got %s", f3.SelectedOneTimePreKey)
	}
}

func TestJWTAlgorithmPinning(t *testing.T) {
	tokenMgr := NewTokenManager("test-secret-key-32-chars-long!!")

	// 1. Valid token generated by TokenManager verifies successfully
	validToken, err := tokenMgr.GenerateDeviceToken("dev-1", "alice", "cli")
	if err != nil {
		t.Fatalf("token generation failed: %v", err)
	}
	claims, err := tokenMgr.ValidateToken(validToken)
	if err != nil || claims.UserHandle != "alice" {
		t.Fatalf("valid token failed validation: %v", err)
	}

	// 2. Token with "alg": "none" MUST be rejected
	noneHeader := "eyJhbGciOiJub25lIiwidHlwIjoiSldUIn0" // {"alg":"none","typ":"JWT"}
	claimsB64 := "eyJ1c2VyX2hhbmRsZSI6ImFsaWNlIiwiZGV2aWNlX2lkIjoiZGV2LTEiLCJleHAiOjk5OTk5OTk5OTl9"
	noneToken := noneHeader + "." + claimsB64 + "."
	_, err = tokenMgr.ValidateToken(noneToken)
	if err == nil {
		t.Fatalf("security violation: TokenManager accepted 'none' algorithm token!")
	}

	// 3. Token with unexpected algorithm (e.g. "RS256") MUST be rejected
	rsHeader := "eyJhbGciOiJSUzI1NiIsInR5cCI6IkpXVCJ9" // {"alg":"RS256","typ":"JWT"}
	rsToken := rsHeader + "." + claimsB64 + ".fakesig"
	_, err = tokenMgr.ValidateToken(rsToken)
	if err == nil {
		t.Fatalf("security violation: TokenManager accepted RS256 algorithm token!")
	}
}


func TestTokenRevocationRegistry(t *testing.T) {
	tokenMgr := NewTokenManager("test-revocation-secret-key-32-chars!")

	token1, err := tokenMgr.GenerateDeviceToken("dev-revoked-1", "alice", "web")
	if err != nil {
		t.Fatal(err)
	}
	token2, err := tokenMgr.GenerateDeviceToken("dev-active-2", "bob", "cli")
	if err != nil {
		t.Fatal(err)
	}

	// Both valid before revocation
	if _, err := tokenMgr.ValidateToken(token1); err != nil {
		t.Fatalf("token1 should be valid, got: %v", err)
	}
	if _, err := tokenMgr.ValidateToken(token2); err != nil {
		t.Fatalf("token2 should be valid, got: %v", err)
	}

	// 1. Revoke token1 specifically
	tokenMgr.RevokeToken(token1)

	if _, err := tokenMgr.ValidateToken(token1); !errors.Is(err, ErrTokenRevoked) {
		t.Fatalf("expected ErrTokenRevoked for revoked token1, got: %v", err)
	}

	// token2 remains valid
	if _, err := tokenMgr.ValidateToken(token2); err != nil {
		t.Fatalf("token2 should still be valid, got: %v", err)
	}

	// 2. Revoke device for token2
	tokenMgr.RevokeDevice("dev-active-2")
	if _, err := tokenMgr.ValidateToken(token2); !errors.Is(err, ErrTokenRevoked) {
		t.Fatalf("expected ErrTokenRevoked for device-revoked token2, got: %v", err)
	}
}
